// One-off: render Natural Earth land (public domain, via world-atlas) to an SVG path string.
// Output: src/web/routes/landing/hero/worldPath.ts — the faint world map behind the hero.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);
// Drop Antarctica for a cleaner silhouette, as in most decorative world maps.
land.features = land.features.map((f) => ({ ...f, geometry: { ...f.geometry, coordinates: f.geometry.coordinates.filter((poly) => Math.max(...poly[0].map((p) => p[1])) > -60) } }));
const projection = geoEquirectangular().fitExtent([[0, 0], [1000, 500]], { type: "Sphere" });
const d = geoPath(projection)(land).replace(/(\d+\.\d)\d+/g, "$1");
writeFileSync(
  new URL("../src/web/routes/landing/hero/worldPath.ts", import.meta.url),
  `/** Natural Earth 1:110m land (public domain), equirectangular, 1000×500 viewBox. Generated by scripts/build-world-map.mjs. */\nexport const WORLD_PATH = ${JSON.stringify(d)};\n`,
);
console.log("world path bytes:", d.length);
